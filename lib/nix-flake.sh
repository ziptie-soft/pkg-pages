#!/bin/sh
# Build a deterministic flake tarball that installs prebuilt release archives pinned by SHA-256.
# Usage: nix-flake.sh --out DIR --name NAME --version VERSION --url-base URL --binaries "A B"
#        --archives "SYSTEM=PATH<newline>SYSTEM=PATH". Output: DIR/flake.tar.gz, flake.nix, flake.lock.
set -eu

lib="$(cd "$(dirname "$0")" && pwd)"
# shellcheck source=common.sh
. "$lib/common.sh"

nixpkgs_ref=nixpkgs-unstable
out='' name='' version='' url_base='' binaries='' archives=''
while [ "$#" -gt 0 ]; do
    [ "$#" -ge 2 ] || die "usage: $0 --out DIR --name NAME --version VERSION --url-base URL --binaries 'A B' --archives 'SYSTEM=PATH…'"
    case "$1" in
        --out) out="$2" ;;
        --name) name="$2" ;;
        --version) version="$2" ;;
        --url-base) url_base="$2" ;;
        --binaries) binaries="$2" ;;
        --archives) archives="$2" ;;
        *) die "unknown option '$1'" ;;
    esac
    shift 2
done
for _opt in "$out" "$name" "$version" "$url_base" "$binaries" "$archives"; do
    [ -n "$_opt" ] || die "usage: --out, --name, --version, --url-base, --binaries and --archives are all required"
done
[ ! -e "$out" ] && [ ! -L "$out" ] || die "out $out already exists"
check_name name "$name"
[ "$name" != default ] || die "name must not be 'default' (it clashes with the flake's default package)"
case "$version" in '' | *[!A-Za-z0-9.+~_-]*) die "version must match [A-Za-z0-9.+~_-]+" ;; esac
check_url url-base "$url_base"
case "$url_base" in *'"'* | *\\* | *'$'* | *'`'* | *' '*) die "url-base contains characters unsafe in a Nix string" ;; esac
case "$binaries" in *"
"* | *"	"*) die "nix-binaries must be a space-separated list on one line" ;; esac

binary_count=0
for binary in $binaries; do
    printf '%s\n' "$binary" | grep -Eq '^[A-Za-z0-9._+-]+(/[A-Za-z0-9._+-]+)*$' || die "binary '$binary' must be a relative path of safe characters"
    case "/$binary/" in */../*) die "binary '$binary' must not contain a '..' segment" ;; esac
    case "$binary" in /*) die "binary '$binary' must not be absolute" ;; esac
    binary_count=$((binary_count + 1))
done
[ "$binary_count" -gt 0 ] || die "nix-binaries must contain at least one binary"

require_tools tar gzip sha256sum grep
tmp=''
make_tmpdir tmp
seen="$tmp/systems"
: > "$seen"
asset_lines="$tmp/assets"
: > "$asset_lines"
systems=''
archive_count=0
while IFS= read -r entry; do
    [ -n "$entry" ] || continue
    case "$entry" in *=*) system=${entry%%=*}; archive=${entry#*=} ;; *) die "nix-archives entries must be SYSTEM=PATH" ;; esac
    [ -n "$system" ] && [ -n "$archive" ] || die "nix-archives entries must be SYSTEM=PATH"
    if grep -Fxq "$system" "$seen"; then die "duplicate Nix system '$system'"; fi
    case "$system" in x86_64-linux | aarch64-linux | x86_64-darwin | aarch64-darwin) ;; *) die "unknown Nix system '$system'" ;; esac
    printf '%s\n' "$system" >> "$seen"
    systems="$systems $system"
    file=${archive##*/}
    printf '%s\n' "$file" | grep -Eq '^[A-Za-z0-9._+-]+\.(tar\.gz|tgz|tar\.xz)$' || die "archive file name '$file' is invalid"
    [ -f "$archive" ] || die "archive '$archive' is not a file"
    case "$file" in
        *.tar.gz | *.tgz) listing="$tmp/listing"; tar -tzf "$archive" > "$listing" ;;
        *.tar.xz) require_tools xz; listing="$tmp/listing"; tar -tJf "$archive" > "$listing" ;;
    esac
    top=''
    while IFS= read -r member; do
        [ -n "$member" ] || continue
        case "$member" in
            /* | . | .. | ./* | ../* | */.. | */../* | */. | */./* | *//*) die "archive '$archive' has an unsafe path '$member'" ;;
            */*) ;;
            *) die "archive '$archive' must have exactly one top-level directory" ;;
        esac
        member_top=${member%%/*}
        if [ -z "$top" ]; then top=$member_top; elif [ "$top" != "$member_top" ]; then
            die "archive '$archive' must have exactly one top-level directory"
        fi
    done < "$listing"
    case "$top" in '' | . | .. | /*) die "archive '$archive' has an unsafe top-level directory" ;; esac
    for binary in $binaries; do
        grep -Fxq "$top/$binary" "$listing" || die "archive '$archive' does not list $top/$binary"
    done
    sum=$(sha256sum "$archive")
    sum=${sum%% *}
    printf '        %s = { url = "%s/%s"; sha256 = "%s"; };\n' "$system" "$url_base" "$file" "$sum" >> "$asset_lines"
    archive_count=$((archive_count + 1))
done <<EOF
$archives
EOF
[ "$archive_count" -gt 0 ] || die "nix-archives must contain at least one archive"

mkdir -p "$out"
cp "$lib/nix/flake.lock" "$out/flake.lock"
# shellcheck disable=SC2086 # split the validated list to take its first entry
set -- $binaries
first_binary=$1
first_basename=${first_binary##*/}
{
    cat <<'NIX_HEAD'
# Generated by pkg-pages (https://github.com/ziptie-soft/pkg-pages). Installs prebuilt release
# binaries pinned by SHA-256; nothing is compiled.
{
NIX_HEAD
    printf '  description = "%s %s (prebuilt release binaries)";\n' "$name" "$version"
    printf '  inputs.nixpkgs.url = "github:NixOS/nixpkgs/%s";\n' "$nixpkgs_ref"
    cat <<'NIX_MID'
  outputs = { self, nixpkgs }:
    let
NIX_MID
    printf '      name = "%s";\n' "$name"
    printf '      version = "%s";\n' "$version"
    printf '      binaries = ['
    for binary in $binaries; do printf ' "%s"' "$binary"; done
    printf ' ];\n      assets = {\n'
    cat "$asset_lines"
    cat <<'NIX_TAIL'
      };
      forAll = f: nixpkgs.lib.genAttrs (builtins.attrNames assets)
        (system: f nixpkgs.legacyPackages.${system} assets.${system});
    in {
      packages = forAll (pkgs: asset: rec {
        default = pkgs.stdenvNoCC.mkDerivation {
          pname = name;
          inherit version;
          src = pkgs.fetchurl { inherit (asset) url sha256; };
          dontConfigure = true;
          dontBuild = true;
          installPhase = ''
            runHook preInstall
            for b in ${pkgs.lib.concatStringsSep " " binaries}; do
              install -Dm755 "$b" "$out/bin/$(basename "$b")"
            done
            runHook postInstall
          '';
NIX_TAIL
    printf '          meta.mainProgram = "%s";\n' "$first_basename"
    cat <<'NIX_END'
        };
        ${name} = default;
      });
    };
}
NIX_END
} > "$out/flake.nix"
tar --sort=name --mtime=@0 --owner=0 --group=0 --numeric-owner -cf - -C "$out" flake.lock flake.nix | gzip -9n > "$out/flake.tar.gz"
log "wrote $out/flake.tar.gz for $name $version ($systems)"
